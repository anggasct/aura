package operation

import (
	"encoding/json"
	"errors"
	"fmt"
	"regexp"
	"slices"
	"strings"

	"github.com/anggasct/aura/internal/platform/command"
	"github.com/anggasct/aura/internal/platform/tools"
)

const (
	maxSummaryBytes     = 120
	maxDescriptionBytes = 1024
	maxToolNameBytes    = 64
	maxToolsPerGroup    = 10
)

var (
	idRule        = regexp.MustCompile(`^[a-z][a-z0-9]*(\.[a-z][a-z0-9-]*){1,2}$`)
	groupRule     = regexp.MustCompile(`^[a-z][a-z0-9]*$`)
	paramNameRule = regexp.MustCompile(`^[a-z][a-z0-9_]{0,31}$`)
)

type ToolLookup interface {
	Definition(name, version string) (tools.Definition, bool)
}

type validation struct {
	tools    ToolLookup
	bindings map[string]*Binding
	checked  bool
	defects  []error
}

func (v *validation) reject(id, format string, args ...any) {
	v.defects = append(v.defects, NewError(ErrorCodeInvalid, fmt.Sprintf("%s: %s", id, fmt.Sprintf(format, args...))))
}

func ValidateCatalogs(catalogs []Catalog) error {
	v := &validation{}
	v.catalogs(catalogs)
	return errors.Join(v.defects...)
}

func knownNeed(name string) bool {
	switch name {
	case "durable", "workflows", "models", "knowledge", "memory", "profile", "plugins", "skills":
		return true
	}
	return false
}

func destinationName(name string) bool {
	switch name {
	case "destination", "channel", "recipient", "address", "target", "to", "alias":
		return true
	}
	return false
}

func (v *validation) catalogs(catalogs []Catalog) {
	groups := map[string]bool{}
	seen := map[string]bool{}
	generatedBy := map[string]string{}
	reserved := reservedGroupNames()
	for i := range catalogs {
		catalog := &catalogs[i]
		name := catalog.Group.Name
		switch {
		case !groupRule.MatchString(name):
			v.reject("group "+name, "the group name does not match its pattern")
		case groups[name]:
			v.reject("group "+name, "the group is declared twice")
		case slices.Contains(reserved, name):
			v.reject("group "+name, "the group collides with a chat command")
		}
		groups[name] = true
		if catalog.Group.Summary == "" || len(catalog.Group.Summary) > maxSummaryBytes {
			v.reject("group "+name, "the group summary is empty or over %d bytes", maxSummaryBytes)
		}
		generated := 0
		for j := range catalog.Descriptors {
			descriptor := &catalog.Descriptors[j]
			if seen[descriptor.ID] {
				v.reject(descriptor.ID, "the id is declared twice")
			}
			seen[descriptor.ID] = true
			v.descriptor(catalog.Group.Name, descriptor)
			if descriptor.GeneratesTool() {
				generated++
				name := ToolName(descriptor.ID)
				if other, taken := generatedBy[name]; taken && other != descriptor.ID {
					v.reject(descriptor.ID, "the tool name %q is also generated by %s", name, other)
				}
				generatedBy[name] = descriptor.ID
			}
		}
		if generated > maxToolsPerGroup {
			v.reject("group "+name, "the group generates %d tools, over %d", generated, maxToolsPerGroup)
		}
	}
	if v.checked {
		v.bindingDefects(catalogs)
	}
}

func reservedGroupNames() []string {
	catalog := command.Catalog()
	var names []string
	for i := range catalog {
		names = append(names, catalog[i].Name)
		names = append(names, catalog[i].Aliases...)
	}
	return names
}

func (v *validation) bindingDefects(catalogs []Catalog) {
	described := map[string]bool{}
	for i := range catalogs {
		for j := range catalogs[i].Descriptors {
			id := catalogs[i].Descriptors[j].ID
			described[id] = true
			if v.bindings[id] == nil {
				v.reject(id, "the descriptor has no binding")
			}
		}
	}
	for id := range v.bindings {
		if !described[id] {
			v.reject(id, "the binding has no descriptor")
		}
	}
}

func (v *validation) descriptor(group string, d *Descriptor) {
	id := d.ID
	if !idRule.MatchString(id) {
		v.reject(id, "the id does not match its pattern")
	} else if segment, _, _ := strings.Cut(id, "."); segment != group {
		v.reject(id, "the first segment is not the group %q", group)
	}
	v.classification(d)
	if d.Summary == "" || len(d.Summary) > maxSummaryBytes {
		v.reject(id, "the summary is empty or over %d bytes", maxSummaryBytes)
	}
	if len(d.Description) > maxDescriptionBytes {
		v.reject(id, "the description is over %d bytes", maxDescriptionBytes)
	}
	v.surfaces(d)
	v.params(d)
	v.output(d)
	if d.Interactive && d.Exposure != ExposureHost {
		v.reject(id, "an interactive operation must be host")
	}
	for _, need := range d.Needs {
		if !knownNeed(need) {
			v.reject(id, "the need %q is unknown", need)
		}
	}
	v.preview(d)
	v.moduleTool(d)
	v.ownerNotice(d)
	v.toolName(d)
}

func (v *validation) classification(d *Descriptor) {
	id := d.ID
	if !d.Exposure.valid() {
		v.reject(id, "the exposure is missing or unknown")
	}
	if !d.Risk.valid() {
		v.reject(id, "the risk is missing or unknown")
	}
	if !d.Commit.valid() {
		v.reject(id, "the commit class is missing or unknown")
	}
	if !d.Risk.valid() || !d.Commit.valid() {
		return
	}
	if d.Risk == RiskRead && (d.Commit != CommitNone || d.FreshApproval) {
		v.reject(id, "a read has no commit class and no fresh approval")
	}
	if d.Risk.effectful() && d.Commit == CommitNone && d.Exposure != ExposureHost {
		v.reject(id, "an effectful operation without a commit class must be host")
	}
}

func (v *validation) surfaces(d *Descriptor) {
	id := d.ID
	if len(d.Surfaces) == 0 {
		if d.SurfaceReason != "" {
			v.reject(id, "a surface reason without a narrowed surface list")
		}
		return
	}
	if d.SurfaceReason == "" {
		v.reject(id, "a narrowed surface list has no reason")
	}
	for _, surface := range d.Surfaces {
		if !surface.valid() || !slices.Contains(exposureSurfaces(d.Exposure), surface) {
			v.reject(id, "the surface %q is not one of the exposure's surfaces", surface)
		}
	}
	if !slices.Contains(d.Surfaces, SurfaceCLI) && (d.Exposure == ExposureOwner || d.Exposure == ExposureHost) {
		v.reject(id, "an owner or host operation keeps the CLI")
	}
}

func (v *validation) preview(d *Descriptor) {
	id := d.ID
	needs := d.Exposure == ExposureAgent && (d.Risk == RiskTrustGrant || d.Risk == RiskDestructive)
	if needs && !d.Preview {
		v.reject(id, "an agent trust grant or deletion needs a preview")
	}
	if d.Risk == RiskRead && d.Preview {
		v.reject(id, "a read has no preview")
	}
	if v.checked && v.bindings[id] != nil {
		bound := v.bindings[id].Preview != nil
		if d.Preview && !bound {
			v.reject(id, "the descriptor declares a preview and the binding has none")
		}
		if !d.Preview && bound {
			v.reject(id, "the binding has a preview and the descriptor declares none")
		}
	}
}

func (v *validation) moduleTool(d *Descriptor) {
	id := d.ID
	if d.ModuleTool == "" {
		return
	}
	if d.Exposure != ExposureAgent {
		v.reject(id, "a module tool projects only an agent operation")
		return
	}
	if v.tools == nil {
		return
	}
	definition, found := v.tools.Definition(d.ModuleTool, tools.Version)
	if !found {
		v.reject(id, "the module tool %q is not registered", d.ModuleTool)
		return
	}
	for _, mismatch := range moduleToolMismatches(d, &definition) {
		v.reject(id, "the module tool %q %s", d.ModuleTool, mismatch)
	}
}

func (v *validation) ownerNotice(d *Descriptor) {
	id := d.ID
	if !d.OwnerNotice {
		return
	}
	if d.Risk != RiskChange || d.Sink || d.FreshApproval {
		v.reject(id, "an owner notice is a plain change and not a sink")
	}
	if d.Exposure != ExposureAgent {
		v.reject(id, "an owner notice is an agent operation")
	}
	for i := range d.Params {
		if destinationName(d.Params[i].Name) {
			v.reject(id, "an owner notice has no destination parameter (%s)", d.Params[i].Name)
		}
	}
	if v.checked && v.bindings[id] != nil && v.bindings[id].RateLimit == nil {
		v.reject(id, "an owner notice has no rate limit binding")
	}
}

func (v *validation) toolName(d *Descriptor) {
	id := d.ID
	if !d.GeneratesTool() {
		return
	}
	name := ToolName(id)
	if len(name) > maxToolNameBytes {
		v.reject(id, "the tool name is over %d bytes", maxToolNameBytes)
	}
	if v.tools != nil {
		if _, taken := v.tools.Definition(name, tools.Version); taken {
			v.reject(id, "the tool name %q is already registered", name)
		}
	}
	if len(d.Display) > 0 {
		schema, err := d.SchemaFor(SurfaceAgent)
		if err == nil {
			err = tools.CheckDisplaySchema(d.Display, schema)
		}
		if err != nil {
			v.reject(id, "the display does not match the agent schema")
		}
	}
}

func (v *validation) output(d *Descriptor) {
	id := d.ID
	if !d.Output.Kind.valid() {
		v.reject(id, "the output kind is missing or unknown")
	}
	names := map[string]bool{}
	for i := range d.Output.Fields {
		field := &d.Output.Fields[i]
		if field.Name == "" || names[field.Name] {
			v.reject(id, "an output field name is empty or repeated")
		}
		names[field.Name] = true
		if field.Secret && d.Exposure != ExposureHost {
			v.reject(id, "the output field %q is secret and the operation is not host", field.Name)
		}
		for _, surface := range field.Surfaces {
			if !surface.valid() {
				v.reject(id, "the output field %q names an unknown surface", field.Name)
			}
		}
	}
}

func (v *validation) params(d *Descriptor) {
	id := d.ID
	if len(d.Params) > maxParams {
		v.reject(id, "the operation declares %d parameters, over %d", len(d.Params), maxParams)
	}
	names := map[string]bool{}
	var positions []int
	restPosition := 0
	for i := range d.Params {
		param := &d.Params[i]
		if !paramNameRule.MatchString(param.Name) || names[param.Name] {
			v.reject(id, "the parameter name %q is invalid or repeated", param.Name)
		}
		names[param.Name] = true
		v.param(id, d.Exposure, d.Projects(SurfaceChat), param)
		if param.Position > 0 {
			positions = append(positions, param.Position)
		}
		if param.Rest {
			restPosition = param.Position
		}
	}
	slices.Sort(positions)
	for index, position := range positions {
		if position != index+1 {
			v.reject(id, "the positions are not contiguous from 1")
			break
		}
	}
	if slices.ContainsFunc(d.Params, func(p Param) bool { return p.Rest }) && (restPosition == 0 || restPosition != len(positions)) {
		v.reject(id, "the rest parameter is not the last positional")
	}
}

func (v *validation) param(id string, exposure Exposure, chat bool, p *Param) {
	name := p.Name
	if !p.Kind.valid() {
		v.reject(id, "the parameter %q has an unknown kind", name)
		return
	}
	for _, surface := range p.Surfaces {
		if !surface.valid() {
			v.reject(id, "the parameter %q names an unknown surface", name)
		}
	}
	if p.Secret && exposure != ExposureHost {
		v.reject(id, "the parameter %q is secret and the operation is not host", name)
	}
	if p.Kind == KindPath && p.Required && chat {
		v.reject(id, "the required path parameter %q can never be supplied in chat", name)
	}
	if p.Prompt != "" && !p.Required {
		v.reject(id, "the optional parameter %q has a prompt", name)
	}
	v.enum(id, p)
	if p.Kind == KindJSON {
		var shape map[string]json.RawMessage
		if json.Unmarshal(p.Schema, &shape) != nil || shape == nil {
			v.reject(id, "the json parameter %q has no schema object", name)
		}
	}
	if len(p.Default) > 0 {
		v.defaultValue(id, p)
	}
}

func (v *validation) enum(id string, p *Param) {
	name := p.Name
	if p.Kind != KindEnum {
		if len(p.Enum) > 0 {
			v.reject(id, "the parameter %q has enum values and is not an enum", name)
		}
		return
	}
	if len(p.Enum) == 0 {
		v.reject(id, "the enum parameter %q has no value", name)
		return
	}
	for _, surface := range p.surfaceList() {
		if surface.valid() && len(p.enumOn(surface)) == 0 {
			v.reject(id, "the enum parameter %q has no value on %s", name, surface)
		}
	}
	for i := range p.Enum {
		for _, surface := range p.Enum[i].Surfaces {
			if !surface.valid() || !p.on(surface) {
				v.reject(id, "the value %q of parameter %q is on a surface the parameter is not", p.Enum[i].Value, name)
			}
		}
	}
}

func (v *validation) defaultValue(id string, p *Param) {
	decoded, err := decodeValue(p.Default)
	if err != nil {
		v.reject(id, "the default of parameter %q is not valid JSON", p.Name)
		return
	}
	for _, surface := range p.surfaceList() {
		if !surface.valid() {
			continue
		}
		if _, err := p.canonicalValue(surface, decoded); err != nil {
			v.reject(id, "the default of parameter %q does not validate on %s", p.Name, surface)
		}
	}
}
